# Type casting = convert a variable from one data type to another
# str(), int(), float(), bool()

name = 'Kaike'
age = 26
distance = 2.2
is_online = True

print(type(name))
print(type(age))
print(type(distance))
print(type(is_online))

print(int(distance))
print(float(age))
print(bool(name))
print(str(age))
print('Age is ' + str(age))
